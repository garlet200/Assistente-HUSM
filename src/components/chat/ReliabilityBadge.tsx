'use client';

/**
 * @file ReliabilityBadge.tsx
 * @description Selo visual de transparência exibido exclusivamente quando a resposta da IA
 * é gerada por um modelo de contingência (Fallback 1, Fallback 2 ou Fallback 3).
 */

import React from 'react';
import { Info } from 'lucide-react';
import {
  CASCADE_CONFIG,
  getTierConfig,
  ModelTier,
  ModelTierConfig,
  ReliabilityLevel,
} from '@/lib/ai/cascadeConfig';

export interface ReliabilityBadgeProps {
  reliability?: ReliabilityLevel;
  modelTier?: ModelTier;
  modelDisplayName?: string;
  style?: React.CSSProperties;
}

function resolveFallbackTierConfig(
  reliability?: ReliabilityLevel,
  modelTier?: ModelTier
): ModelTierConfig | undefined {
  if (modelTier) {
    return getTierConfig(modelTier);
  }
  if (reliability) {
    return CASCADE_CONFIG.find((tierConfig) => tierConfig.reliability.level === reliability);
  }
  return undefined;
}

/**
 * Neutral reliability badge displayed inside AI response bubbles.
 * Appears ONLY when the response was generated by a fallback model (never for primary).
 */
export function ReliabilityBadge({
  reliability,
  modelTier,
  modelDisplayName,
  style,
}: ReliabilityBadgeProps) {
  if (reliability === 'high' || modelTier === 'primary' || (!reliability && !modelTier)) {
    return null;
  }

  const tierConfig = resolveFallbackTierConfig(reliability, modelTier);
  if (!tierConfig || !tierConfig.reliability.badgeVisible) {
    return null;
  }

  const resolvedModelName = modelDisplayName || tierConfig.displayName;
  const tooltipText = `Resposta gerada via contingência (${tierConfig.badgeLabel} — ${resolvedModelName}).`;

  return (
    <span
      style={{
        display: 'inline-flex',
        alignItems: 'center',
        gap: 'var(--spacing-min)',
        background: 'var(--color-semantic-backgroundcolor-backgrounddimmer)',
        border: 'var(--strokewidth-min) solid var(--color-primitive-greyblue-greyblue-300)',
        color: 'var(--color-semantic-text-textdark)',
        padding: '2px var(--spacing-sm)',
        borderRadius: 'var(--radius-radius-full)',
        fontSize: 'var(--typography-fontsizes-caption)',
        fontWeight: 'var(--typography-fontweights-semibold)',
        fontFamily: 'var(--typography-fontfamilies-mainsans)',
        lineHeight: 'var(--typography-lineheights-body-caption)',
        ...style,
      }}
      title={tooltipText}
    >
      <Info size={12} style={{ flexShrink: 0, color: 'var(--color-semantic-text-textdark)' }} />
      {tierConfig.badgeLabel} • {resolvedModelName}
    </span>
  );
}
